-- Builds ../SchizzlesWarriorSetup/Data.lua for the WoW Forever copy of the helper.
-- Run from this folder: lua build.lua   (Lua 5.1, the same as the game). "lua build.lua --check" only compares.
-- The addon profiles are shared with the MoP Classic kit, so they are read from there; the console variables and the
-- Details! profile string are Forever's own pieces.
local MOP = "../../../../../WoW Classic - Mists of Pandaria/Schizzle's Warrior/AddOns/"
local SOURCES = {
	{ key = "Bartender4", file = MOP .. "Bartender4/Profile.lua" },
	{ key = "Keybinds", file = MOP .. "Bartender4/Keybinds.lua" },
	{ key = "Prat 3.0", file = MOP .. "Prat 3.0/Profile.lua" },
	{ key = "SexyMap", file = MOP .. "SexyMap/Profile.lua" },
	{ key = "Questie", file = MOP .. "Questie/Profile.lua" },
	{ key = "GatherMate2", file = MOP .. "GatherMate2/Profile.lua" },
	{ key = "TomTom", file = MOP .. "TomTom/Profile.lua" },
	{ key = "CVars", file = "CVars.lua" },
}
-- Plain strings, stored as they are: the Details! import string (the Arms profile; Forever's spec is the whole class)
-- and the Musca Auras pack.
local STRINGS = {
	{ key = "Details", file = MOP .. "Details!/Arms Profile.txt" },
	-- Schizzle's Warrior Essentials for Musca Auras (/schizzle auras); built in ../Musca Auras/source.
	{ key = "MuscaWarrior", file = "../../Musca Auras/Schizzle's Warrior Essentials.txt" },
}

local function read(path)
	local f = assert(io.open(path, "rb"))
	local s = f:read("*a")
	f:close()
	return s
end

local out = {
	"-- Generated by source/build.lua from the per-addon Profile.lua / Keybinds.lua files. Don't edit by hand.",
	"local _, ns = ...",
	"ns.data = {}",
}
for _, s in ipairs(SOURCES) do
	local body = read(s.file)
	assert(type(assert(loadstring(body, s.file))()) == "table", s.file .. " must return a table")
	out[#out + 1] = ("ns.data[%q] = (function()\n%s\nend)()"):format(s.key, body:gsub("%s+$", ""))
end
for _, s in ipairs(STRINGS) do
	local body = read(s.file):gsub("^%s+", ""):gsub("%s+$", "")
	assert(not body:find("[\r\n]"), s.file .. " must be one line")
	out[#out + 1] = ("ns.data[%q] = %q"):format(s.key, body)
end
local text = table.concat(out, "\n") .. "\n"

local target = "../SchizzlesWarriorSetup/Data.lua"
if arg and arg[1] == "--check" then
	local ok, cur = pcall(read, target)
	if not ok or cur ~= text then
		print("Data.lua is out of date: run lua build.lua")
		os.exit(1)
	end
	print("Data.lua is up to date")
	return
end
local f = assert(io.open(target, "wb"))
f:write(text)
f:close()
print("wrote " .. target .. " (" .. #text .. " bytes)")
