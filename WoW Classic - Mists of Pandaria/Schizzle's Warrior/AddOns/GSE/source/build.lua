-- Builds the GSE import string and the readable sheet from sequence.lua.
-- Usage: lua build.lua   (LibDeflate must be on disk: WA_LIBS, default /workspace)
local HERE = (arg and arg[0] and arg[0]:match("^(.*)/[^/]*$")) or "."
local F = dofile(HERE .. "/gse_format.lua")
local S = dofile(HERE .. "/sequence.lua")
local OUT = HERE .. "/../Schizzle's Warrior Level 8.txt"
local SHEET = HERE .. "/../Level 8 Sequences (readable).md"

local function sequenceTable(def)
  local actions = {}
  for _, b in ipairs(def.blocks) do
    actions[#actions + 1] = {Type = "Action", type = "macro", macro = b.macro}
  end
  return {
    LastUpdated = S.lastUpdated,
    MetaData = {
      Author = S.author, Default = 1, EnforceCompatability = true, GSEVersion = S.gseVersion,
      Helplink = S.helplink, ManualIntervention = true, Name = def.name, SpecID = S.specID,
      TOC = S.toc, Talents = {},
    },
    Versions = {{Label = def.label, Actions = actions, InbuiltVariables = {}}},
    WeakAuras = {},
  }
end

local function build()
  local seqs, count = {}, 0
  for _, def in ipairs(S.sequences) do seqs[def.name] = sequenceTable(def); count = count + 1 end
  return {type = "COLLECTION",
    payload = {ElementCount = count, Macros = {}, Sequences = seqs, Variables = {}}}
end

local export = F.encode(build())
local f = assert(io.open(OUT, "wb")); f:write(export); f:close()

local lines = {
  "# Schizzle's Warrior level 8 GSE sequences (readable)",
  "",
  "Generated by `source/build.lua` from `source/sequence.lua`. This is what the import string holds, block by block.",
  "GSE plays one block per key press, in order, then starts again from the top.",
  "",
}
for _, def in ipairs(S.sequences) do
  lines[#lines + 1] = "## " .. def.name .. " (version \"" .. def.label .. "\")"
  lines[#lines + 1] = ""
  lines[#lines + 1] = def.note
  lines[#lines + 1] = ""
  for i, b in ipairs(def.blocks) do
    lines[#lines + 1] = ("### Block %d: %s (%d of 255 characters)"):format(i, b.title, #b.macro)
    lines[#lines + 1] = ""
    lines[#lines + 1] = "```"
    lines[#lines + 1] = b.macro
    lines[#lines + 1] = "```"
    lines[#lines + 1] = ""
  end
end
f = assert(io.open(SHEET, "wb")); f:write(table.concat(lines, "\n")); f:close()
print(("wrote %d chars to %s"):format(#export, OUT))
