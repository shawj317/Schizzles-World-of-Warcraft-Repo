-- Builds ../SchizzlesWarriorSetup/Data.lua from the per-addon data files in the sibling folders.
-- Run from this folder: lua build.lua   (Lua 5.1, the same as the game)
-- Each source file is a plain "return { ... }" table, so it is wrapped in a function and stored
-- in ns.data[<key>]. Every file is loaded first, so a syntax error stops the build.
local SOURCES = {
	{ key = "Bartender4", file = "../../Bartender4/Profile.lua" },
	{ key = "Keybinds", file = "../../Bartender4/Keybinds.lua" },
	{ key = "Prat 3.0", file = "../../Prat 3.0/Profile.lua" },
	{ key = "SexyMap", file = "../../SexyMap/Profile.lua" },
	{ key = "Questie", file = "../../Questie/Profile.lua" },
	{ key = "GatherMate2", file = "../../GatherMate2/Profile.lua" },
	{ key = "TomTom", file = "../../TomTom/Profile.lua" },
}

local function read(path)
	local f = assert(io.open(path, "rb"))
	local s = f:read("*a")
	f:close()
	return s
end

local out = {
	"-- Generated by source/build.lua from the per-addon Profile.lua / Keybinds.lua files. Don't edit by hand.",
	"local _, ns = ...",
	"ns.data = {}",
}
for _, s in ipairs(SOURCES) do
	local body = read(s.file)
	assert(type(assert(loadstring(body, s.file))()) == "table", s.file .. " must return a table")
	out[#out + 1] = ("ns.data[%q] = (function()\n%s\nend)()"):format(s.key, body:gsub("%s+$", ""))
end
local text = table.concat(out, "\n") .. "\n"

local target = "../SchizzlesWarriorSetup/Data.lua"
if arg and arg[1] == "--check" then
	local ok, cur = pcall(read, target)
	if not ok or cur ~= text then
		print("Data.lua is out of date: run lua build.lua")
		os.exit(1)
	end
	print("Data.lua is up to date")
	return
end
local f = assert(io.open(target, "wb"))
f:write(text)
f:close()
print("wrote " .. target .. " (" .. #text .. " bytes)")
